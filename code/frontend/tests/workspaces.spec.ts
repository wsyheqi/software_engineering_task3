  expect(await page.locator('.guest-stay').count()).toBeGreaterThanOrEqual(2)
  const response = await page.request.get('/api/me/stays')
  const body = await response.text()
  expect(body).toContain('138****5678')
  expect(body).not.toMatch(/"price"|"total"|"ruleJson"|冯琳|13912345678/)
