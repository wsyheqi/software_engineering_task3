import { test, expect, type Page } from '@playwright/test'
import fs from 'node:fs'
fs.mkdirSync('../docs/screenshots', {recursive: true})
async function login(page: Page, username: string) {
  await page.goto('/')
  await page.getByLabel('账号', {exact: true}).fill(username)
  await page.getByLabel('密码', {exact: true}).fill('Demo@123456')
  await page.getByRole('button', {name: '登录工作空间', exact: true}).click()
  await expect(page.getByRole('navigation', {name: '工作空间导航'})).toBeVisible()
}
const errors: string[] = []
test.beforeEach(async ({page}) => {errors.length = 0; page.on('pageerror', error => errors.push(error.message))})
test.afterEach(() => expect(errors).toEqual([]))
test('学校接待人员可以查询、确认预订并取消整单', async ({page}) => {
  await login(page, 'reception')
  await expect(page.getByRole('heading', {name: '住宿预订', exact: true})).toBeVisible()
  await page.getByRole('button', {name: '查询酒店', exact: true}).click()
  await expect(page.locator('.hotel-option')).toHaveCount(3)
  await page.screenshot({path: '../docs/screenshots/reception.png', fullPage: true})
  await page.getByRole('button', {name: '查看方案并确认', exact: true}).first().click()
  const quote = page.getByRole('dialog', {name: '确认住宿方案'})
  await expect(quote.getByText('取消期限与适用费用规则')).toBeVisible()
  await quote.getByRole('checkbox').check()
  await quote.getByRole('button', {name: '确认并自动预订'}).click()
  const order = page.getByRole('dialog', {name: /^订单 CR/})
  await expect(order).toBeVisible()
  await expect(order.locator('.badge').first()).toHaveText('已确认')
  await order.getByRole('button', {name: '修改住宿方案'}).click()
  const change = page.getByRole('dialog', {name: '改订方案与差额确认'})
  await change.getByRole('button', {name: '查询新方案'}).click()
  await change.locator('.compact-option').filter({hasText: '湖畔商务酒店'}).getByRole('button', {name: '查看方案'}).click()
  await change.getByRole('checkbox').check()
  let orderListRequests = 0
  page.on('request', request => {
    if (request.method() === 'GET' && request.url().endsWith('/api/bookings')) orderListRequests++
  })
  await change.getByRole('button', {name: '确认差额并执行改订'}).click()
  await expect(order.getByRole('heading', {name: '湖畔商务酒店', exact: true})).toBeVisible()
  expect(orderListRequests).toBe(1)
  await order.getByRole('button', {name: '整单取消', exact: true}).click()
  await page.getByRole('dialog', {name: '整单取消', exact: true}).getByRole('button', {name: '确认处理'}).click()
  await expect(order.locator('.badge').first()).toHaveText('已取消')
})
test('酒店工作区显示真实房源与逐人到店事实', async ({page}) => {
  await login(page, 'hotel')
  await expect(page.getByRole('heading', {name: '每日房源与价格', exact: true})).toBeVisible()
  await expect(page.locator('.inventory-table tbody tr')).toHaveCount(21)
  await page.screenshot({path: '../docs/screenshots/inventory.png', fullPage: true})
  const price = page.locator('.inventory-table tbody tr').first().getByRole('spinbutton').first()
  const original = await price.inputValue()
  await price.fill(String(Number(original) + 1))
  await page.getByRole('button', {name: '保存房源调整'}).click()
  await expect(page.getByRole('button', {name: '保存房源调整'})).toBeDisabled()
  await expect(price).toHaveValue(String(Number(original) + 1))
  await price.fill(original)
  await page.getByRole('button', {name: '保存房源调整'}).click()
  await expect(page.getByRole('button', {name: '保存房源调整'})).toBeDisabled()
  await page.getByRole('navigation').getByRole('button', {name: '入住与到店处理'}).click()
  const current = page.getByRole('row').filter({has: page.locator('.badge-checked_in')}).first()
  await current.getByRole('button', {name: '查看与处理'}).click()
  const detail = page.getByRole('dialog', {name: /^订单 CR/})
  await expect(detail.getByRole('heading', {name: '计划来宾与实际到店'})).toBeVisible()
  await expect(detail.getByText('陈浩', {exact: true})).toBeVisible()
  await expect(detail.getByText('冯琳', {exact: true})).toBeVisible()
  await expect(detail.getByRole('button', {name: '登记实际间夜'})).toBeVisible()
})
